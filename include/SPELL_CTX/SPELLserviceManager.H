/*@{*/


// FORWARD REFERENCES ////////////////////////////////////////////////////////
// TYPES /////////////////////////////////////////////////////////////////////
// DEFINES ///////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////
/**
 ** \brief
 **
 ** \par Description:
 **
 ** \par Usage:
 **
 ** \par Synchronization:
 **
**////////////////////////////////////////////////////////////////////////////
class SPELLserviceManager
{
public: //--------------------------------------------------------------------

    // ENUMS /////////////////////////////////////////////////////////////////

		typedef enum ErrorCode_
		{
			UNKNOWN_PROC_ID,
			SERVICE_FAILED_STARTUP,
			SERVICE_CRASHED,
			UNKNOWN
		}
		ErrorCode;

	// EXCEPTIONS ////////////////////////////////////////////////////////////

		typedef struct OperationError_
		{
			std::string message;
			ErrorCode   errorCode;
		}
		OperationError;

    // TYPES /////////////////////////////////////////////////////////////////

		typedef std::list<std::string> ServiceList;

    // LIFECYCLE /////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Constructor.
		**////////////////////////////////////////////////////////////////////
		SPELLserviceManager();

		//////////////////////////////////////////////////////////////////////
		/** Destructor.
		**////////////////////////////////////////////////////////////////////
		~SPELLserviceManager();

    // STATIC ////////////////////////////////////////////////////////////////

		static SPELLserviceManager& instance();

    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Start a service
		**////////////////////////////////////////////////////////////////////
		void startService( SPELLserviceStartupParams& config );

		//////////////////////////////////////////////////////////////////////
		/** Stop an executor
		**////////////////////////////////////////////////////////////////////
		void closeService(std::string& serviceId );

		//////////////////////////////////////////////////////////////////////
		/** Kill an executor
		**////////////////////////////////////////////////////////////////////
		void killService( const std::string& serviceId );

		//////////////////////////////////////////////////////////////////////
		/** Kill all executors
		**////////////////////////////////////////////////////////////////////
		void killAll();

		//////////////////////////////////////////////////////////////////////
		/** Check for active executors
		**////////////////////////////////////////////////////////////////////
		unsigned int getNumActiveServices();

		//////////////////////////////////////////////////////////////////////
		/** Obtain an available instance identifier
		**////////////////////////////////////////////////////////////////////
		std::string getInstanceId( const std::string& serviceId );

		//////////////////////////////////////////////////////////////////////
		/** Initialize the manager
		**////////////////////////////////////////////////////////////////////
		void setup( const std::string& contextName );

		//////////////////////////////////////////////////////////////////////
		/** Cleanup the manager
		**////////////////////////////////////////////////////////////////////
		void cleanup();

		//////////////////////////////////////////////////////////////////////
		/** Obtain a given executor
		**////////////////////////////////////////////////////////////////////
		SPELLservice* getService( const std::string& serviceId );

		//////////////////////////////////////////////////////////////////////
		/** Obtain list of existing executors
		**////////////////////////////////////////////////////////////////////
		ServiceList getServiceList();

		//////////////////////////////////////////////////////////////////////
		/** Report an executor lost
		**////////////////////////////////////////////////////////////////////
		void serviceLost( SPELLservice& service );

		//////////////////////////////////////////////////////////////////////
		/** Mark executor to be cleared
		**////////////////////////////////////////////////////////////////////
		void clearService( const std::string& instanceId );

		//////////////////////////////////////////////////////////////////////
        /** Closes a service
        **////////////////////////////////////////////////////////////////////
        void closeService( const std::string& instanceId );

		//////////////////////////////////////////////////////////////////////
		/** Complete the message with executor information
		**////////////////////////////////////////////////////////////////////
		void buildServiceInfo( const std::string& serviceId, SPELLipcMessage& msg );

		//////////////////////////////////////////////////////////////////////
		/** Delete files corresponding to the given executor
		**////////////////////////////////////////////////////////////////////
		void deleteServiceFiles( const SPELLserviceStartupParams& config );

	// DATA MEMBERS //////////////////////////////////////////////////////////

protected: //-----------------------------------------------------------------

		friend class ServiceLoginMonitor;

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////

		void callback_serviceReconnected( const std::string& instanceId );
		void callback_serviceNotReconnected( const std::string& instanceId );

    // DATA MEMBERS //////////////////////////////////////////////////////////

private: //-------------------------------------------------------------------
		friend class SPELLexecutorManager;
    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////

		typedef std::map<std::string,SPELLservice*> ServiceMap;
		typedef std::list<int> InstanceList;
		typedef std::map<std::string,InstanceList> InstanceMap;
		typedef std::list<std::string> IdentifierList;

    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Prepare to executor reconnection in case of starting after crash
		**////////////////////////////////////////////////////////////////////
		void reconnectServices();

		void addServiceModel( SPELLservice* exec );

		void removeServiceModel( const std::string& instanceId );

		bool hasInstanceNumber( const std::string& serviceId, int instanceNum );

		void addInstanceNumber( const std::string& serviceId, int instanceNum );

		void clearModels();

    // DATA MEMBERS //////////////////////////////////////////////////////////

		/** Synchronization lock */
		SPELLmutex	m_lock;
		/** Holds the singleton instance */
		static SPELLserviceManager* s_instance;
		/** Holds the map of existing executors */
		ServiceMap m_services;
		/** Holds the map of existing instance numbers */
		InstanceMap m_instances;
		/** Holds the context name */
		std::string m_contextName;
		/** Holds the list of executors to be cleared next time */
		IdentifierList m_toClear;
		/** Holds the persistency table for executors */
		SPELLpersistencyTable* m_persisTable;
		/** Orphan executors pending login */
		ServiceMap m_pendingLogin;

};

/*@}*/
#endif
