#ifndef __SPELL_RESOURCE_MANAGER_H__
#define __SPELL_RESOURCE_MANAGER_H__

// FILES TO INCLUDE ////////////////////////////////////////////////////////
// System includes ---------------------------------------------------------
// Local includes ----------------------------------------------------------
#include "SPELL_EXC/SPELLframeManager.H"
// Project includes --------------------------------------------------------
#include "SPELL_SYN/SPELLqueue.H"

/** \addtogroup SPELL_EXC */
/*@{*/


// FORWARD REFERENCES //////////////////////////////////////////////////////
// TYPES ///////////////////////////////////////////////////////////////////
// DEFINES /////////////////////////////////////////////////////////////////

#define RESOURCE_MONITOR_CHANGE_RESOURCE "changeResource"
#define RESOURCE_MONITOR_GET_RESOURCES "getResources"

//////////////////////////////////////////////////////////////////////////////
/**
 ** \brief Resource manager
 **
**////////////////////////////////////////////////////////////////////////////
class SPELLresourceManager
{
public: //--------------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Constructor.
		**////////////////////////////////////////////////////////////////////
		SPELLresourceManager( SPELLframeManager& frameManager );

		//////////////////////////////////////////////////////////////////////
		/** Destructor.
		**////////////////////////////////////////////////////////////////////
		~SPELLresourceManager();

    // STATIC ////////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Enable or disable the manager.
		**////////////////////////////////////////////////////////////////////
		void setEnabled( bool enabled );

		//////////////////////////////////////////////////////////////////////
		/** Check enabled
		**////////////////////////////////////////////////////////////////////
		bool isEnabled();

		//////////////////////////////////////////////////////////////////////
		/** Analysis on demand
		**////////////////////////////////////////////////////////////////////
		void analyze();

		//////////////////////////////////////////////////////////////////////
		/** Get available resources.
		 *
		 * \return The list of resources.
		**////////////////////////////////////////////////////////////////////
		void getResources();

		//////////////////////////////////////////////////////////////////////
		/** Change a resource value.
		 *
		 * \param resource IN: the resource data.
		 *
		**////////////////////////////////////////////////////////////////////
		void changeResource( SPELLresourceInfo& resource );

		//////////////////////////////////////////////////////////////////////
		/** Check if the internal executor status is valid to process
		 * resource manipulation.
		 *
		 * \returns True if the status is valid.
		**////////////////////////////////////////////////////////////////////
		bool isStatusValid();

		//////////////////////////////////////////////////////////////////////
		/** Call resource monitor method.
		 *
		 * \param moitorTask IN: name of the method to call.
		 *
		**////////////////////////////////////////////////////////////////////
		void callResourceMonitorFromClient(std::string monitorTask);

    // DATA MEMBERS //////////////////////////////////////////////////////////

protected: //-----------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////
    // DATA MEMBERS //////////////////////////////////////////////////////////

private: //-------------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////
    // DATA MEMBERS //////////////////////////////////////////////////////////
		/** Holds reference to the frame manager */
		SPELLframeManager& m_frameManager;
		/** Queue to store resources to change */
		SPELLqueue<SPELLresourceInfo> m_changeResourceQueue;
};

/*@}*/
#endif
