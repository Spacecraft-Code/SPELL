//////////////////////////////////////////////////////////////////////////////
/**
 ** \brief Listener for resource changes.
 **
**////////////////////////////////////////////////////////////////////////////
class SPELLresourceChangeListener
{
public:

	//////////////////////////////////////////////////////////////////////
	/** Notify about a resource change.
	 *
	 * \param changed IN: list of changed resources.
	 *
	**////////////////////////////////////////////////////////////////////
	 void resourceChanged( const std::vector<SPELLresourceInfo>& changed );

	//////////////////////////////////////////////////////////////////////
	/** Notify about a resource list.
	 *
	 * \param changed IN: list of resources.
	 *
	**////////////////////////////////////////////////////////////////////
	 void resourceList( const std::vector<SPELLresourceInfo>& resources );
};

//////////////////////////////////////////////////////////////////////////////
/**
 ** \brief Monitor of resources
 **
 ** \par Description and usage:
 **
 ** 	Used to implement the display-of-resurces mechanism
 **
**////////////////////////////////////////////////////////////////////////////
class SPELLresourceMonitor: public SPELLresourceChangeListener
{
public: //--------------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////

		/** Type for resource name-value map */
		typedef std::map<std::string,SPELLresourceInfo> ResourceMap;

    // LIFECYCLE /////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Constructor.
		**////////////////////////////////////////////////////////////////////
		SPELLresourceMonitor( SPELLresourceChangeListener* listener );

		//////////////////////////////////////////////////////////////////////
		/** Destructor.
		**////////////////////////////////////////////////////////////////////
		~SPELLresourceMonitor();

    // STATIC ////////////////////////////////////////////////////////////////

		static bool s_enabled;

    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Get available resources.
		 *
		 * \return The list of resources.
		**////////////////////////////////////////////////////////////////////
		void getResources();

		//////////////////////////////////////////////////////////////////////
		/** Change resource
		 *
		 * \param resource IN: the resource to change.
		 *
		**////////////////////////////////////////////////////////////////////
		void changeResource( SPELLresourceInfo& resource );

		//////////////////////////////////////////////////////////////////////
		/** Get resource value.
		 *
		 * \param resourceName IN: resource name
		 *
		 * \return The resource information.
		**////////////////////////////////////////////////////////////////////
		void getResource( SPELLresourceInfo& resource );

		//////////////////////////////////////////////////////////////////////
		/** Analyze resource dictionary to detect changes.
		**////////////////////////////////////////////////////////////////////
		void analyze();

		//////////////////////////////////////////////////////////////////////
		/** Initialize the resource dictionary
		**////////////////////////////////////////////////////////////////////
		void initialize();

protected: //-----------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////
    // DATA MEMBERS //////////////////////////////////////////////////////////

private: //-------------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Retrieve existing resources, local or global
		 *  \param resultingMap OUT: map of resource information to fill.
		 *  \param isLocal IN: whether to retrieve local resources (true) or global (false).
		 *  \param onlyLocal IN: whether to ONLY retrieve the values of local resources
		 *						Neither the type, global value or ValueRange are retrieved 
		 *
		**////////////////////////////////////////////////////////////////////
		void retrieveResources( ResourceMap &resultingMap, bool onlyLocal=false );

		//////////////////////////////////////////////////////////////////////
		/** Retrieve resource value range and name map
		**////////////////////////////////////////////////////////////////////
		void retrieveResourceValueRangeAndNameMap( );

		//////////////////////////////////////////////////////////////////////
		/** Check if a resource should not be monitored
		**////////////////////////////////////////////////////////////////////
		bool shouldDiscard( const std::string& name );

    // DATA MEMBERS //////////////////////////////////////////////////////////

		/** Reference to the frame */
		PyFrameObject* m_frame;
		/** Scope name */
		std::string m_scopeName;
		/** Initialized flag */
		bool m_initialized;
		/** Reference to the single change listener */
		SPELLresourceChangeListener* m_listener;
		/** Map of resources */
		ResourceMap m_resources;
		/** Resources accepted values */
		std::map<std::string, std::vector<std::pair<std::string, std::string> > > m_resourceAcceptedValues;
		/** Resources SPELL/GCS name mapping */
		std::map<std::string, std::string> m_resourceNameMapping;
};

