#ifndef __SPELL_RESOURCE_BUFFER_H__
#define __SPELL_RESOURCE_BUFFER_H__

// FILES TO INCLUDE ////////////////////////////////////////////////////////
// System includes ---------------------------------------------------------
// Local includes ----------------------------------------------------------
// Project includes --------------------------------------------------------
#include "SPELL_EXC/SPELLresourceInfo.H"
#include "SPELL_SYN/SPELLthread.H"
#include "SPELL_SYN/SPELLthread.H"
#include "SPELL_IPC/SPELLipcMessage.H"
#include "SPELL_SYN/SPELLmutex.H"

/** \addtogroup SPELL_CIFS */
/*@{*/


// FORWARD REFERENCES //////////////////////////////////////////////////////
class SPELLserverCif;
// TYPES ///////////////////////////////////////////////////////////////////
// DEFINES /////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////
/**
 ** \brief Buffer for RDOTCO messages
 **
**////////////////////////////////////////////////////////////////////////////
class SPELLresourceBuffer : public SPELLthread
{
public: //--------------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Constructor.
		**////////////////////////////////////////////////////////////////////
		SPELLresourceBuffer( const std::string& procId, SPELLserverCif& cif );

		//////////////////////////////////////////////////////////////////////
		/** Destructor.
		**////////////////////////////////////////////////////////////////////
		~SPELLresourceBuffer();

    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Main thread method
		**////////////////////////////////////////////////////////////////////
		void run();

		//////////////////////////////////////////////////////////////////////
		/** Stop the buffer
		**////////////////////////////////////////////////////////////////////
		void stop();

		//////////////////////////////////////////////////////////////////////
		/** Send a resource update message
		**////////////////////////////////////////////////////////////////////
		void resourceChange( const std::vector<SPELLresourceInfo>& changed );

		//////////////////////////////////////////////////////////////////////
		/** Send a resource list message
		**////////////////////////////////////////////////////////////////////
		void resourceList( const std::vector<SPELLresourceInfo>& resources );

		//////////////////////////////////////////////////////////////////////
		/** Collect the accumulated information and send the IPC message.
		**////////////////////////////////////////////////////////////////////
		void flush();

protected: //-----------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // STATIC ////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////

private: //-------------------------------------------------------------------

    // EXCEPTIONS ////////////////////////////////////////////////////////////
    // ENUMS /////////////////////////////////////////////////////////////////
    // TYPES /////////////////////////////////////////////////////////////////
    // STATIC ////////////////////////////////////////////////////////////////
    // LIFECYCLE /////////////////////////////////////////////////////////////
    // METHODS ///////////////////////////////////////////////////////////////

		//////////////////////////////////////////////////////////////////////
		/** Check if data available
		**////////////////////////////////////////////////////////////////////
		bool hasDataToSend();

	// DATA MEMBERS //////////////////////////////////////////////////////////

		/** Holds the reference to the CIF */
		SPELLserverCif& m_cif;
		/** Working flag */
		bool m_working;
		/** Synchronization lock */
		SPELLmutex m_lock;
		/** Notification message skeletons */
		SPELLipcMessage m_resourceMessage;
		/** List of added, updated and removed resources
		 * Note that it is a map, so updates overwrite:
		 * if a resource is added, then right away modified, then right away removed,
		 * only the removal effect will remain
		 * */
		std::map<std::string,SPELLresourceInfo> m_resources;
		/** Accumulation of notifications */
		unsigned int m_total;
		/** state whether the flush contain result of GetResources */
		bool m_bufferHasListResources;
};

/*@}*/
#endif
